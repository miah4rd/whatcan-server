async function loadFromServer(apiUrl) {
  const statusEl = $("apiStatus");

  async function tryUrl(url) {
    const res = await fetch(settingsUrl(url), { signal: AbortSignal.timeout(6000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  }

  let data = null;
  try {
    data = await tryUrl(apiUrl);
  } catch (e) {
    if (apiUrl !== DEFAULT_API) {
      try {
        data = await tryUrl(DEFAULT_API);
        $("apiUrl").value = DEFAULT_API;
        chrome.storage.local.set({ apiUrl: DEFAULT_API });
      } catch (e2) {
        statusEl.textContent = "\u26a0 Could not reach server \u2014 showing defaults";
        statusEl.className = "api-status err";
        return;
      }
    } else {
      statusEl.textContent = "\u26a0 Could not reach server \u2014 showing defaults";
      statusEl.className = "api-status err";
      return;
    }
  }

  // Prefer new followupSteps format; fall back to legacy followupDelays
  if (Array.isArray(data.followupSteps) && data.followupSteps.length > 0) {
    _fuSteps = data.followupSteps.map((s) => ({
      delayMs: s.delayMs,
      message: s.message || "",
    }));
    renderFuSteps(_fuSteps);
  } else if (Array.isArray(data.followupDelays) && data.followupDelays.length > 0) {
    _fuSteps = data.followupDelays.map((delayMs) => ({ delayMs, message: "" }));
    renderFuSteps(_fuSteps);
  }

  if (Array.isArray(data.qualificationSteps) && data.qualificationSteps.length > 0) {
    _qualSteps = data.qualificationSteps.map((s) => ({
      label: s.label || "",
      message: s.message || "",
    }));
    renderQualSteps(_qualSteps);
  }

  if (Array.isArray(data.brokerPicks) && data.brokerPicks.length > 0) {
    _segments = data.brokerPicks;
    renderSegments(_segments);
  }

  statusEl.textContent = "\u2713 Connected to server";
  statusEl.className = "api-status ok";
}

