$("save").addEventListener("click", async () => {
  const apiUrl = $("apiUrl").value.trim() || DEFAULT_API;
  const statusEl = $("status");
  statusEl.textContent = "Saving\u2026";

  await new Promise((resolve) =>
    chrome.storage.local.set(
      {
        guide: $("guide").value.trim() || DEFAULT_GUIDE,
        urlFilter: $("urlFilter").value.trim(),
        brokerName: $("brokerName").value.trim() || "",
        outputLanguage: $("outputLanguage").value || "English",
        dictationLang: $("dictationLang").value,
        apiUrl,
      },
      resolve,
    ),
  );

  const followupSteps = readFuSteps();
  const qualificationSteps = readQualSteps();
  const brokerPicks = readSegments();

  try {
    const res = await fetch(settingsUrl(apiUrl), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ followupSteps, qualificationSteps, brokerPicks }),
      signal: AbortSignal.timeout(8000),
    });
    if (!res.ok) {
      const body = await res.text().catch(() => "");
      throw new Error(`Server error ${res.status}: ${body}`);
    }
    statusEl.textContent = "Saved.";
    $("apiStatus").textContent = "\u2713 Settings saved to server";
    $("apiStatus").className = "api-status ok";
  } catch (e) {
    statusEl.textContent = "Local saved. Server error: " + e.message;
    $("apiStatus").textContent = "\u26a0 Could not save settings to server";
    $("apiStatus").className = "api-status err";
  }

  setTimeout(() => (statusEl.textContent = ""), 3000);
});

