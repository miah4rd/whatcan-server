function settingsUrl(apiUrl) {
  return apiUrl.replace(/\/suggest$/, "/settings");
}

function escHtml(str) {
  return (str || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// ── Follow-up steps UI ─────────────────────────────────────────────────────

let _fuSteps = DEFAULT_FU_STEPS.map((s) => ({ ...s }));

function renderFuSteps(steps) {
  const container = $("fuSteps");
  container.innerHTML = "";
  steps.forEach((step, idx) => {
    const days = (step.delayMs / MS_PER_DAY).toFixed(1).replace(/\.0$/, "");
    const hasMsg = (step.message || "").trim().length > 0;
    const div = document.createElement("div");
    div.className = "fu-step";
    div.dataset.idx = idx;
    div.innerHTML = `
      <div class="fu-step-head">
        <span class="fu-step-num">Follow-up ${idx + 1}</span>
        <div class="fu-delay-wrap">
          <input type="number" class="fu-delay" min="0.1" step="0.5"
                 value="${escHtml(days)}" data-idx="${idx}" title="Delay in days" />
          <span class="fu-delay-unit">days after silence</span>
        </div>
        ${steps.length > 1 ? `<button class="fu-del-btn" data-del="${idx}" title="Remove step">&#215;</button>` : ""}
      </div>
      <div class="fu-msg-label">
        Fixed message &nbsp;<span>(optional)</span> &mdash; leave empty so AI writes it based on conversation
      </div>
      <textarea class="fu-msg ${hasMsg ? "has-preset" : ""}"
        placeholder="Leave empty — AI generates a context-aware message automatically"
        data-idx="${idx}">${escHtml(step.message || "")}</textarea>`;
    container.appendChild(div);
  });

  // highlight textarea when it has content
  container.querySelectorAll(".fu-msg").forEach((ta) => {
    ta.addEventListener("input", () => {
      ta.classList.toggle("has-preset", ta.value.trim().length > 0);
    });
  });
}

function readFuSteps() {
  const steps = [];
  $("fuSteps").querySelectorAll(".fu-step").forEach((div) => {
    const idx = parseInt(div.dataset.idx, 10);
    const daysRaw = parseFloat(div.querySelector(`.fu-delay[data-idx="${idx}"]`).value) || 1;
    const delayMs = Math.round(daysRaw * MS_PER_DAY);
    const message = (div.querySelector(`.fu-msg[data-idx="${idx}"]`).value || "").trim();
    steps.push({ delayMs, message: message || undefined });
  });
  return steps;
}

$("fuSteps").addEventListener("click", (e) => {
  const btn = e.target.closest("[data-del]");
  if (!btn) return;
  _fuSteps = readFuSteps();
  const idx = parseInt(btn.dataset.del, 10);
  _fuSteps.splice(idx, 1);
  renderFuSteps(_fuSteps);
});

$("fuAdd").addEventListener("click", () => {
  _fuSteps = readFuSteps();
  const lastDelay = _fuSteps.length > 0 ? _fuSteps[_fuSteps.length - 1].delayMs : 5 * MS_PER_DAY;
  _fuSteps.push({ delayMs: lastDelay + 2 * MS_PER_DAY, message: "" });
  renderFuSteps(_fuSteps);
  const cards = $("fuSteps").querySelectorAll(".fu-step");
  cards[cards.length - 1]?.scrollIntoView({ behavior: "smooth", block: "nearest" });
});

