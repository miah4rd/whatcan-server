// Auto-detect current amoCRM user and pre-fill broker name
(async () => {
  try {
    const tabs = await new Promise(r => chrome.tabs.query({ active: true, currentWindow: true }, r));
    const tab = tabs?.[0];
    if (!tab?.url?.includes("amocrm.ru")) return;
    const results = await chrome.scripting.executeScript({
      target: { tabId: tab.id },
      func: async () => {
        // 1. Try amoCRM JS global
        try {
          const u = window.AMOCRM?.constant?.("currentUser") || window.AMOCRM?.data?.currentUser;
          if (u?.name) return u.name.split(/\s+/)[0].trim();
        } catch {}
        // 2. Try DOM
        const domSelectors = [".user-widget__name", ".user__name", ".profile-card__name", ".header__user-name"];
        for (const sel of domSelectors) {
          const txt = document.querySelector(sel)?.textContent?.trim();
          if (txt) return txt.split(/\s+/)[0];
        }
        // 3. API users list
        try {
          const accResp = await fetch("/api/v4/account", { credentials: "include" });
          if (!accResp.ok) return null;
          const accData = await accResp.json();
          const userId = accData.current_user_id;
          if (!userId) return null;
          const usersResp = await fetch("/api/v4/users?limit=50", { credentials: "include" });
          if (!usersResp.ok) return null;
          const usersData = await usersResp.json();
          const user = (usersData?._embedded?.users || []).find(u => u.id === userId);
          return user?.name?.split(/\s+/)?.[0]?.trim() || null;
        } catch { return null; }
      },
    });
    const detected = results?.[0]?.result;
    if (detected) {
      $("brokerName").value = detected;
      const hint = document.createElement("div");
      hint.style.cssText = "font-size:11px;color:#4ade80;margin-top:3px";
      hint.textContent = `✓ Auto-detected from amoCRM: ${detected}`;
      $("brokerName").after(hint);
    }
  } catch { /* scripting API not available */ }
})();

